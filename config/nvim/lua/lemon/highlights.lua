    bg = p.base,
    bg_dark = p.mantle, -- statusline, tabline, sidebars
    bg_darkest = p.crust, -- the strip behind everything
    bg_float = p.mantle,
    bg_sel = p.selected,
    bg_hover = p.hover,
    bg_hl = p.surface0, -- cursorline, folds, visual
    bg_danger = p.dangerBg,
    border = p.divider,
    border_strong = p.surface1,

    fg = p.text,
    fg_dim = p.subtext0,
    fg_dimmer = p.overlay0,
    fg_bright = p.subtext1,
    muted = p.surface2, -- non-text, indent guides

