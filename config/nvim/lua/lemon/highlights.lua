  -- Some palettes spend one hex on two keys: Everforest's `mauve` and `green`
  -- are the same green, Gruvbox's `mauve` and `pink` the same rose. That is
  -- harmless in the bar, where those two never sit next to each other, but in
  -- code it makes keywords indistinguishable from strings. Fall through to the
  -- first alternative that is genuinely a different color.
  ---@param preferred string
  ---@param clashes string[] colors `preferred` must not equal
  ---@param alternatives string[] tried in order
  ---@return string
  local function distinct(preferred, clashes, alternatives)
    local function collides(color)
      for _, other in ipairs(clashes) do
        if color:lower() == other:lower() then
          return true
        end
      end
      return false
    end

    if not collides(preferred) then
      return preferred
    end
    for _, alternative in ipairs(alternatives) do
      if not collides(alternative) then
        return alternative
      end
    end
    return preferred
  end

