-- Turns a palette (lua/lemon/palette.lua) into the full highlight table.
-- One mapping serves every theme in palettes.json, so a new theme block gets a
-- matching editor for free and all of them look like the same editor.
--
-- The role assignment is fixed on purpose — mauve is the accent, blue the
-- function color, green strings — because the palettes keep their keys in the
-- same roles the bar uses them in. On Monochrome, where every accent is a
-- shade of grey, this comes out as a tonal scheme rather than a broken one.
-- The one exception is `distinct()` below, for palettes that give two keys the
-- same hex.

local Palette = require("lemon.palette")

local M = {}

---@param p table palette from lemon.palette
---@return table<string, table> highlight groups
function M.build(p)
  local blend = Palette.blend
